import { MongoClient, ObjectId } from 'mongodb';
import 'dotenv/config';

// Get MongoDB URL and ensure username/password are properly encoded
let MONGO_URL = process.env.MONGO_URL || 'mongodb://localhost:27017/dna-pulse';

// If MONGO_URL contains ${MONGO_PASSWORD}, replace it with encoded password
if (MONGO_URL.includes('${MONGO_PASSWORD}') && process.env.MONGO_PASSWORD) {
  const encodedPassword = encodeURIComponent(process.env.MONGO_PASSWORD);
  MONGO_URL = MONGO_URL.replace('${MONGO_PASSWORD}', encodedPassword);
}

// Always encode username and password in connection string to handle special characters
if (MONGO_URL.startsWith('mongodb+srv://') || MONGO_URL.startsWith('mongodb://')) {
  try {
    const urlPattern = /^(mongodb(\+srv)?:\/\/)([^@]+)@(.+)$/;
    const match = MONGO_URL.match(urlPattern);

    if (match) {
      const [, protocol, , credentials, rest] = match;
      const [username, password] = credentials.split(':');

      if (username && password) {
        const decodedUsername = decodeURIComponent(username);
        const decodedPassword = decodeURIComponent(password);
        const encodedUsername = encodeURIComponent(decodedUsername);
        const encodedPassword = encodeURIComponent(decodedPassword);
        MONGO_URL = `${protocol}${encodedUsername}:${encodedPassword}@${rest}`;
      }
    }
  } catch (e) {
    console.warn('URL encoding failed, using original URL');
  }
}

const DB_NAME = process.env.MONGO_DB_NAME || 'dna-pulse';

async function seedDetectionData() {
  const client = new MongoClient(MONGO_URL);

  try {
    await client.connect();
    console.log(`✅ Connected to MongoDB: ${DB_NAME}\n`);

    const db = client.db(DB_NAME);

    // Get the first organization
    const orgsCol = db.collection('organizations');
    const org = await orgsCol.findOne({});

    if (!org) {
      console.error('❌ No organization found. Please create an organization first.');
      process.exit(1);
    }

    const organizationId = org._id;
    console.log(`📋 Using organization: ${org.name} (${organizationId})\n`);

    // 1. Create a sample detection rule
    console.log('📝 Creating sample detection rule...');
    const rulesCol = db.collection('rules');

    // Check if rule already exists
    const existingRule = await rulesCol.findOne({
      organization_id: organizationId,
      name: 'High Severity Events Spike',
    });

    let ruleId;
    if (existingRule) {
      console.log('⏭️  Rule already exists, using existing rule');
      ruleId = existingRule._id;
    } else {
      const rule = {
        organization_id: organizationId,
        name: 'High Severity Events Spike',
        query: 'severity:high OR severity:critical',
        condition: {
          type: 'count',
          threshold: 5,
          time_window_min: 5,
        },
        severity: 'high',
        tags: ['security', 'monitoring'],
        enabled: true,
        schedule_sec: 60,
        cooldown_min: 5,
        last_run_at: null,
        created_by: 'seed-script',
        created_at: new Date(),
        updated_at: new Date(),
      };

      const result = await rulesCol.insertOne(rule);
      ruleId = result.insertedId;
      console.log(`✅ Created rule: ${rule.name} (${ruleId})\n`);
    }

    // 2. Generate sample events that match the rule
    console.log('📊 Generating sample events...');
    const eventsCol = db.collection('events');

    const now = new Date();
    const events = [];

    for (let i = 0; i < 10; i++) {
      const timestamp = new Date(now.getTime() - i * 30 * 1000); // 30 seconds apart

      events.push({
        event_id: `seed-event-${Date.now()}-${i}`,
        organization_id: organizationId,
        data_source_id: new ObjectId(),
        agent_id: new ObjectId(),
        type: 'security_event',
        source: 'test-source',
        payload: {
          '@ts': timestamp.toISOString(),
          severity: i % 2 === 0 ? 'high' : 'critical',
          event_type: 'security_alert',
          host: `server-${(i % 3) + 1}`,
          user: `user-${(i % 5) + 1}`,
          service: 'api-gateway',
          message: `Test security event ${i + 1}`,
          description: `This is a test event generated by the seed script`,
        },
        created_at: timestamp,
        ingested_at: timestamp,
      });
    }

    await eventsCol.insertMany(events);
    console.log(`✅ Created ${events.length} sample events\n`);

    // 3. Wait a moment and check if rule engine created an alert
    console.log('⏳ Waiting 5 seconds for rule engine to process...');
    await new Promise((resolve) => setTimeout(resolve, 5000));

    const alertsCol = db.collection('alerts');
    const alerts = await alertsCol
      .find({
        organization_id: organizationId,
        rule_id: ruleId,
      })
      .toArray();

    if (alerts.length > 0) {
      console.log(`✅ Rule engine created ${alerts.length} alert(s):`);
      alerts.forEach((alert) => {
        console.log(`   - ${alert.title} (${alert.status}, ${alert.severity})`);
      });
    } else {
      console.log('⏳ No alerts created yet. Rule engine will evaluate on next cycle (60s).');
      console.log('   You can manually trigger evaluation or wait for the scheduled run.');
    }

    console.log('\n✅ Seed data created successfully!');
    console.log('\n📋 Summary:');
    console.log(`   - Organization: ${org.name}`);
    console.log(`   - Rule: High Severity Events Spike`);
    console.log(`   - Events: ${events.length} test events`);
    console.log(`   - Alerts: ${alerts.length} (will be created by rule engine)\n`);

    console.log('🔍 Next steps:');
    console.log(
      '   1. Start the rule engine: docker compose -f docker-compose.dev.yml up -d rule-engine'
    );
    console.log('   2. Check rule engine logs: docker logs -f dnapulse-rule-engine');
    console.log('   3. Navigate to Detection & Investigation page in the UI');
    console.log('   4. View the rule and wait for alerts to be generated\n');
  } catch (error) {
    console.error('❌ Error seeding data:', error);
    process.exit(1);
  } finally {
    await client.close();
    console.log('✅ MongoDB connection closed');
  }
}

seedDetectionData();
